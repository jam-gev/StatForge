using System;
using System.Collections.Generic;
using System.Text;
using System.Text.RegularExpressions;

namespace StatForge.Editor
{
    /// <summary>One stat id found in the project, with the asset it came from (used in error messages).</summary>
    public readonly struct StatIdSource
    {
        public readonly string Id;
        public readonly string AssetPath;

        public StatIdSource(string id, string assetPath)
        {
            Id = id;
            AssetPath = assetPath;
        }
    }

    /// <summary>Generation was stopped; <see cref="Errors"/> lists every problem found, not only the first.</summary>
    public sealed class StatIdGenerationException : Exception
    {
        public IReadOnlyList<string> Errors { get; }

        public StatIdGenerationException(IReadOnlyList<string> errors)
            : base("StatIds generation failed:\n" + string.Join("\n", errors))
        {
            Errors = errors;
        }
    }

    /// <summary>
    /// Turns stat ids into a C# constants class. Pure (no AssetDatabase, no file IO) so it can be unit tested;
    /// <see cref="StatIdGeneratorMenu"/> feeds it the project's StatDefinition assets.
    /// Output is deterministic (ordinal sort, '\n' line endings), so regenerating unchanged assets gives the same text.
    /// </summary>
    public static class StatIdCodeGenerator
    {
        public const string DefaultClassName = "StatIds";

        private static readonly Regex IdentifierPattern = new Regex("^[A-Za-z_][A-Za-z0-9_]*$");

        private static readonly HashSet<string> CSharpKeywords = new HashSet<string>(StringComparer.Ordinal)
        {
            "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const",
            "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit",
            "extern", "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int",
            "interface", "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out",
            "override", "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed",
            "short", "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try",
            "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
        };

        /// <exception cref="StatIdGenerationException">Empty, duplicate, or not usable as a C# identifier.</exception>
        public static string Generate(IEnumerable<StatIdSource> sources, string className = DefaultClassName, string namespaceName = null)
        {
            if (sources == null)
            {
                throw new ArgumentNullException(nameof(sources));
            }

            var errors = new List<string>();
            var pathById = new Dictionary<string, string>(StringComparer.Ordinal);

            foreach (StatIdSource source in sources)
            {
                string id = source.Id;

                if (string.IsNullOrWhiteSpace(id))
                {
                    errors.Add($"Empty StatId in '{source.AssetPath}'");
                    continue;
                }

                if (!IdentifierPattern.IsMatch(id) || CSharpKeywords.Contains(id))
                {
                    errors.Add($"StatId '{id}' in '{source.AssetPath}' is not a valid C# identifier (letters, digits, '_', not starting with a digit, not a keyword)");
                    continue;
                }

                if (pathById.TryGetValue(id, out string existingPath))
                {
                    errors.Add($"Duplicate StatId '{id}' in '{existingPath}' and '{source.AssetPath}'");
                    continue;
                }

                pathById.Add(id, source.AssetPath);
            }

            if (errors.Count > 0)
            {
                throw new StatIdGenerationException(errors);
            }

            var ids = new List<string>(pathById.Keys);
            ids.Sort(StringComparer.Ordinal);

            return Write(ids, className, namespaceName);
        }

        private static string Write(List<string> ids, string className, string namespaceName)
        {
            int width = 0;
            for (int i = 0; i < ids.Count; i++)
            {
                width = Math.Max(width, ids[i].Length);
            }

            bool hasNamespace = !string.IsNullOrEmpty(namespaceName);
            string indent = hasNamespace ? "    " : string.Empty;

            var sb = new StringBuilder();
            sb.Append("// <auto-generated/>\n");
            sb.Append("// Tools > StatForge > Generate StatIds. Do not edit by hand.\n");
            sb.Append("using StatForge;\n\n");

            if (hasNamespace)
            {
                sb.Append("namespace ").Append(namespaceName).Append("\n{\n");
            }

            sb.Append(indent).Append("public static class ").Append(className).Append('\n');
            sb.Append(indent).Append("{\n");

            for (int i = 0; i < ids.Count; i++)
            {
                string id = ids[i];
                sb.Append(indent).Append("    public static readonly StatId ").Append(id.PadRight(width))
                  .Append(" = new StatId(\"").Append(id).Append("\");\n");
            }

            sb.Append(indent).Append("}\n");

            if (hasNamespace)
            {
                sb.Append("}\n");
            }

            return sb.ToString();
        }
    }
}
