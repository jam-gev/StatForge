using NUnit.Framework;
using StatForge.Editor;

namespace StatForge.Tests
{
    public class StatIdCodeGeneratorTests
    {
        private static StatIdSource Src(string id, string path = null)
        {
            return new StatIdSource(id, path ?? $"Assets/Stats/{id}.asset");
        }

        private static StatIdGenerationException GenerateFails(params StatIdSource[] sources)
        {
            return Assert.Throws<StatIdGenerationException>(() => StatIdCodeGenerator.Generate(sources));
        }

        [Test]
        public void Generate_TwoIds_SortedAndAligned()
        {
            string code = StatIdCodeGenerator.Generate(new[] { Src("Health"), Src("AttackSpeed") });

            const string expected =
                "// <auto-generated/>\n" +
                "// Tools > StatForge > Generate StatIds. Do not edit by hand.\n" +
                "using StatForge;\n" +
                "\n" +
                "public static class StatIds\n" +
                "{\n" +
                "    public static readonly StatId AttackSpeed = new StatId(\"AttackSpeed\");\n" +
                "    public static readonly StatId Health      = new StatId(\"Health\");\n" +
                "}\n";

            Assert.AreEqual(expected, code);
        }

        [Test]
        public void Generate_WithNamespace_WrapsClass()
        {
            string code = StatIdCodeGenerator.Generate(new[] { Src("Health") }, "GameStats", "MyGame");

            StringAssert.Contains("namespace MyGame\n{\n    public static class GameStats\n", code);
            StringAssert.Contains("        public static readonly StatId Health = new StatId(\"Health\");\n", code);
        }

        [Test]
        public void Generate_SameInputDifferentOrder_SameOutput()
        {
            string a = StatIdCodeGenerator.Generate(new[] { Src("Mana"), Src("Health"), Src("Armor") });
            string b = StatIdCodeGenerator.Generate(new[] { Src("Armor"), Src("Mana"), Src("Health") });

            Assert.AreEqual(a, b);
        }

        [Test]
        public void Generate_OrdinalSort_UppercaseBeforeLowercase()
        {
            // Ordinal, not culture: same order on every machine, so the file never changes by itself.
            string code = StatIdCodeGenerator.Generate(new[] { Src("armor"), Src("Health") });

            Assert.Less(code.IndexOf("Health", System.StringComparison.Ordinal), code.IndexOf("armor", System.StringComparison.Ordinal));
        }

        [Test]
        public void Generate_NoIds_EmptyClass()
        {
            string code = StatIdCodeGenerator.Generate(new StatIdSource[0]);

            StringAssert.EndsWith("public static class StatIds\n{\n}\n", code);
        }

        [Test]
        public void Generate_Duplicate_FailsWithBothPaths()
        {
            StatIdGenerationException e = GenerateFails(Src("Health", "Assets/A.asset"), Src("Health", "Assets/B.asset"));

            Assert.AreEqual(1, e.Errors.Count);
            StringAssert.Contains("Assets/A.asset", e.Errors[0]);
            StringAssert.Contains("Assets/B.asset", e.Errors[0]);
        }

        [Test]
        public void Generate_DifferentCase_IsNotDuplicate()
        {
            // StatId compares ordinal (case-sensitive), so these are two different stats, and two valid C# names.
            string code = StatIdCodeGenerator.Generate(new[] { Src("Health"), Src("health") });

            StringAssert.Contains("StatId Health", code);
            StringAssert.Contains("StatId health", code);
        }

        [TestCase("Attack Speed")]
        [TestCase("1Hp")]
        [TestCase("Crit-Rate")]
        [TestCase("event")]
        [TestCase("class")]
        public void Generate_NotACSharpIdentifier_FailsWithPath(string id)
        {
            StatIdGenerationException e = GenerateFails(Src(id, "Assets/Bad.asset"));

            Assert.AreEqual(1, e.Errors.Count);
            StringAssert.Contains("Assets/Bad.asset", e.Errors[0]);
        }

        [TestCase(null)]
        [TestCase("")]
        [TestCase("   ")]
        public void Generate_EmptyId_FailsWithPath(string id)
        {
            StatIdGenerationException e = GenerateFails(Src(id, "Assets/Empty.asset"));

            StringAssert.Contains("Assets/Empty.asset", e.Errors[0]);
        }

        [Test]
        public void Generate_SeveralProblems_ReportsAllAtOnce()
        {
            StatIdGenerationException e = GenerateFails(
                Src("Health", "Assets/A.asset"),
                Src("Health", "Assets/B.asset"),
                Src("event"),
                Src(""));

            Assert.AreEqual(3, e.Errors.Count);
        }

        [Test]
        public void GeneratedConstant_EqualsIdStoredInAsset()
        {
            // The generated class builds its own StatId; it must still find the stat added from the asset.
            StatDefinition definition = Shared.TestStatDefinitions.Create(new StatId("Health"), 100f);
            try
            {
                var container = new StatContainer();
                container.AddStat(definition);

                var generated = new StatId("Health"); // what StatIds.Health holds
                Assert.AreEqual(100f, container.GetValue(generated));
            }
            finally
            {
                Shared.TestStatDefinitions.Destroy(definition);
            }
        }
    }
}
